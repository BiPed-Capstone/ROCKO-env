/**
 * AddFeedforwardController is the last controller in the balance cascade, one instance per wheel
 * (left_ and right_add_feedforward_controller in rocko_controllers.yaml). It is chainable: it
 * exposes one reference interface per command interface, and each cycle writes
 *     wheel velocity command = reference (from pitch_pid_controller) + feedforward (topic)
 * to its command interface (<wheel>_joint/velocity on the motor plugin). It always writes a value:
 * a missing reference becomes a stop (findings H-2, H-7), a failed write is counted (M-5).
 *
 * Tipover cutoff (finding H-4). It also reads the pitch state [deg] of its wheel's joint
 * (<wheel>_joint/pitch, the IMU's pitch). If |pitch| goes past tipover_pitch_deg (proposed 35 deg),
 * it writes 0.0 every cycle from then on, and stays that way until an operator publishes
 * std_msgs/msg/Empty on /tipover_rearm while |pitch| <= rearm_max_pitch_deg (proposed 10 deg). The
 * controller stays active (it is not deactivated), so it keeps writing that 0.0. Each instance
 * latches on its own from its own pitch reading; both read the same IMU value, so both trip in the
 * same cycle. Both subscribe to the ONE absolute topic /tipover_rearm, so a single publish re-arms
 * both wheels together (a per-instance topic would let an operator re-arm one wheel and leave the
 * other at zero). See TipoverLatch.hpp for the exact rules and why zero output is right only after
 * a fall.
 */
