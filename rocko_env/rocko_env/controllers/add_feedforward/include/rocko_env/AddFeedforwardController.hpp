using DataType = std_msgs::msg::Float64MultiArray;
class AddFeedforwardController : public controller_interface::ChainableControllerInterface
{
public:
  controller_interface::CallbackReturn on_init() override;

  controller_interface::InterfaceConfiguration command_interface_configuration() const override;

  controller_interface::InterfaceConfiguration state_interface_configuration() const override;

  controller_interface::CallbackReturn on_configure(
    const rclcpp_lifecycle::State & previous_state) override;

  controller_interface::CallbackReturn on_activate(
    const rclcpp_lifecycle::State & previous_state) override;

  controller_interface::CallbackReturn on_deactivate(
    const rclcpp_lifecycle::State & previous_state) override;

  bool on_set_chained_mode(bool chained_mode) override;

  controller_interface::return_type update_and_write_commands(
    const rclcpp::Time & time, const rclcpp::Duration & period) override;

protected:
  std::vector<hardware_interface::CommandInterface> on_export_reference_interfaces() override;

  controller_interface::return_type update_reference_from_subscribers(
    const rclcpp::Time & time, const rclcpp::Duration & period) override;

  std::shared_ptr<add_feedforward_controller::ParamListener> param_listener_;
  add_feedforward_controller::Params params_;

  realtime_tools::RealtimeBuffer<std::shared_ptr<DataType>> rt_buffer_ptr_;
  rclcpp::Subscription<DataType>::SharedPtr joints_cmd_sub_;

  std::vector<std::string> reference_interface_names_;

  std::vector<std::string> command_interface_names_;

  // SAFETY PARAMETERS (proposed values; a human confirms them on the robot). Edit and rebuild;
  // they are not ROS parameters.
  // How many control cycles in a row set_value() may fail before update returns ERROR (finding
  // M-5). Nominally 50 ms at update_rate 100.
  static constexpr unsigned kMaxConsecutiveWriteFailures = 5;  // [cycles]
  // Minimum time between repeats of the same throttled log line in this controller.
  static constexpr int kLogThrottleMs = 1000;  // [ms]
  // How many control cycles in a row a NaN reference is covered by repeating the last finite
  // command before 0.0 is written. Nominally 3 x 10 ms = 30 ms at update_rate 100.
  // This count is in cycles, so this controller must run at the SAME rate as
  // pitch_pid_controller (the one writing the reference): both inherit update_rate 100 today.
  // If they ran at different rates, "3 cycles" would not mean the same time for both.
  static constexpr unsigned kMaxStaleReferenceCycles = 3;  // [cycles]

  // Counters below are only touched in the update loop (one thread).
  unsigned long failed_command_writes_{0};      // [writes] set_value() returned false, total
  unsigned consecutive_write_failures_{0};      // [cycles] cycles in a row with a failed write
  unsigned long rejected_commands_{0};          // [commands] non-finite commands refused, total
  // One entry per command interface, sized in on_configure (never in the update loop).
  std::vector<double> last_command_;            // [wheel velocity, same unit as the reference]
  std::vector<unsigned> stale_reference_cycles_;  // [cycles] NaN references in a row

private:
  void topic_callback(const std_msgs::msg::Float64::SharedPtr msg)
  {
    // A NaN or inf feedforward would poison every wheel command (reference + NaN = NaN), so a
    // non-finite message is ignored and the previous finite value stays in effect.
    if (!std::isfinite(msg->data))
    {
      return;
    }
    _feedforward.store(msg->data, std::memory_order_relaxed);
  }
  rclcpp::Subscription<std_msgs::msg::Float64>::SharedPtr subscription_;

  // Written by the executor thread (topic_callback), read by the 100 Hz update thread, hence atomic.
  // Added to the wheel velocity reference. 0.0 until the first message arrives.
  std::atomic<double> _feedforward{0.0};
  static_assert(
    std::atomic<double>::is_always_lock_free,
    "_feedforward is read in the real-time loop and must not take a lock");
};
